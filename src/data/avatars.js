const AVATARS_BY_ID = Object.fromEntries(
  AVATAR_CATEGORIES.flatMap((category) => category.avatars.map((avatar) => [avatar.id, avatar])),
);

export const getAvatar = (id) => (id ? (AVATARS_BY_ID[id] ?? null) : null);

export function randomAvatarId(exclude = []) {
  const pool = Object.keys(AVATARS_BY_ID).filter((id) => !exclude.includes(id));
  const source = pool.length ? pool : Object.keys(AVATARS_BY_ID);
  return source[Math.floor(Math.random() * source.length)];
}
